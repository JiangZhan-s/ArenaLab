CREATE TABLE IF NOT EXISTS players (
 id BIGINT PRIMARY KEY, epoch BIGINT NOT NULL DEFAULT 0, ws_consumed BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS matches (
 id VARCHAR(64) PRIMARY KEY, p0 BIGINT NOT NULL, p1 BIGINT NOT NULL,
 state JSON NOT NULL, status VARCHAR(24) NOT NULL DEFAULT 'running',
 ready0 BOOLEAN NOT NULL DEFAULT FALSE, ready1 BOOLEAN NOT NULL DEFAULT FALSE,
 deadline DATETIME(6) NOT NULL, owner VARCHAR(64) NOT NULL,
 owner_epoch BIGINT NOT NULL DEFAULT 1, lease_until DATETIME(6) NOT NULL,
 policy VARCHAR(16) NOT NULL DEFAULT 'recover',
 rules_version VARCHAR(32) NOT NULL DEFAULT 'turn-v1', season VARCHAR(32) NOT NULL DEFAULT 's1'
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS commands (
 match_id VARCHAR(64) NOT NULL, player_id BIGINT NOT NULL,
 command_id VARCHAR(128) NOT NULL, payload_hash CHAR(64) NOT NULL,
 response JSON NOT NULL, PRIMARY KEY(match_id,player_id,command_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS events (
 match_id VARCHAR(64) NOT NULL, version BIGINT NOT NULL,
 state JSON NOT NULL, reason VARCHAR(24) NOT NULL,
 PRIMARY KEY(match_id,version)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS results (
 match_id VARCHAR(64) PRIMARY KEY, result_id VARCHAR(128) NOT NULL UNIQUE,
 winner INT NOT NULL, state VARCHAR(24) NOT NULL DEFAULT 'pending'
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ledger (
 match_id VARCHAR(64) NOT NULL, player_id BIGINT NOT NULL, delta INT NOT NULL,
 PRIMARY KEY(match_id,player_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ratings (
 player_id BIGINT PRIMARY KEY, score BIGINT NOT NULL DEFAULT 0, version BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tickets (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, player_id BIGINT NOT NULL,
 request_id VARCHAR(128) NOT NULL, status VARCHAR(24) NOT NULL,
 match_id VARCHAR(64) NOT NULL DEFAULT '', UNIQUE KEY request_key(player_id,request_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS occupancy (
 player_id BIGINT PRIMARY KEY, match_id VARCHAR(64) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ds_instances (
 id VARCHAR(64) PRIMARY KEY, endpoint VARCHAR(256) NOT NULL,
 build VARCHAR(64) NOT NULL, region VARCHAR(32) NOT NULL,
 status VARCHAR(24) NOT NULL, last_seen DATETIME(6) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS allocations (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, player_id BIGINT NOT NULL,
 request_id VARCHAR(128) NOT NULL, instance_id VARCHAR(64) NOT NULL,
 generation BIGINT NOT NULL, match_id VARCHAR(64) NOT NULL,
 status VARCHAR(24) NOT NULL, build VARCHAR(64) NOT NULL, region VARCHAR(32) NOT NULL,
 UNIQUE KEY allocation_request(player_id,request_id), UNIQUE KEY allocated_match(match_id)
) ENGINE=InnoDB;
